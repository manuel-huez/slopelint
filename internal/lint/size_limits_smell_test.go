// sizeLimitSource puts half of long's statements in a closure, whose
// statements count toward long.
func sizeLimitSource(header string, statements, params, results int) string {
	inner := statements / 2

	return header + "package sample\n\nfunc long() {\n\tf := func() {\n" + strings.Repeat(
		"\t\t_ = 0\n",
		inner,
	) +
		"\t}\n\tf()\n" + strings.Repeat(
		"\t_ = 0\n",
		statements-inner-2,
	) +
		"}\n\nfunc params(" + strings.Repeat(
		"_ int, ",
		params,
	) + ") {}\n\n" +
		"func results() (" + strings.Repeat(
		"int, ",
		results,
	) + ") { panic(0) }\n"
}

func TestDetectsFunctionSizeLimits(t *testing.T) {
	t.Parallel()

	tmp := newTestModule(t)
	writeFile(t, filepath.Join(tmp, "sample.go"), sizeLimitSource("", 41, 7, 4))

	joined := joinMessages(lintInDir(t, tmp))
	for _, want := range []string{
		`function "long" has 41 statements; the largest statement is at line 4 (21); ` +
			"the closure at line 4 (20) uses nothing from the function, so it can move out",
		`function "params" has 7 parameters`,
		`function "results" returns 4 results`,
	} {
		if !strings.Contains(joined, want) {
			t.Fatalf("expected %q, got:\n%s", want, joined)
		}
	}
}

func TestSkipsFunctionSizeLimitsAtLimitTestAndGenerated(t *testing.T) {
	t.Parallel()

	tmp := newTestModule(t)
	writeFile(t, filepath.Join(tmp, "sample.go"), sizeLimitSource("", 40, 6, 3))
	writeFile(t, filepath.Join(tmp, "gen.go"), strings.ReplaceAll(
		sizeLimitSource(
			"// Code generated by test. DO NOT EDIT.\n",
			41,
			7,
			4,
		),
		"func ",
		"func gen",
	))
	writeFile(t, filepath.Join(tmp, "sample_test.go"), strings.ReplaceAll(
		sizeLimitSource("", 41, 7, 4), "func ", "func test"))

	issues := lintInDir(t, tmp)
	for _, kind := range []string{"long_function", "long_param_list", "long_result_list"} {
		if hasIssueKind(issues, kind) {
			t.Fatalf("unexpected %s finding, got:\n%s", kind, joinMessages(issues))
		}
	}
}

func methodSource(header, receiver, prefix string, count int) string {
	var source strings.Builder

	source.WriteString(header + "package sample\n\n")

	for index := range count {
		fmt.Fprintf(&source, "func (%s) %s%d() {}\n", receiver, prefix, index)
	}

	return source.String()
}

func TestDetectsGodReceiver(t *testing.T) {
	t.Parallel()

	tmp := newTestModule(t)
	writeFile(t, filepath.Join(tmp, "big.go"),
		methodSource("", "b *big[T]", "pointer", 21)+"\ntype big[T any] struct{}\n")
	// A function taking *big first counts as a method; one taking big does not.
	writeFile(t, filepath.Join(tmp, "big_more.go"), methodSource("", "b big[T]", "value", 19)+
		"func moved[T any](b *big[T]) {}\nfunc byValue[T any](b big[T]) {}\n")

	// Embedded package types add their methods; sync.Mutex, here behind an
	// alias, is not counted.
	writeFile(t, filepath.Join(tmp, "wide.go"), methodSource("", "w *wide", "own", 21)+
		"\ntype wide struct{ part; mutex }\n")
	writeFile(t, filepath.Join(tmp, "mutex.go"),
		"package sample\n\nimport \"sync\"\n\ntype mutex = sync.Mutex\n")
	writeFile(
		t,
		filepath.Join(tmp, "part.go"),
		methodSource("", "p part", "part", 20)+"\ntype part struct{}\n",
	)

	// A helper embedded by two types is shared, so it adds to neither.
	writeFile(t, filepath.Join(tmp, "shared.go"), methodSource("", "s shared", "shared", 20)+
		"\ntype shared struct{}\ntype left struct{ shared }\ntype right struct{ shared }\n")
	writeFile(t, filepath.Join(tmp, "sides.go"), methodSource("", "l left", "left", 21)+
		methodSource("", "r right", "right", 21)[len("package sample\n\n"):])

	// Parts of one client embed each other, and one is reached through a
	// named field; none of them is shared outside the client, so all count.
	writeFile(t, filepath.Join(tmp, "client.go"), methodSource("", "c *client", "own", 5)+
		"\ntype client struct{ request; catalog; objects; derived store }\n"+
		"type request struct{ *catalog; *objects }\n"+
		"type store struct{ *catalog }\n"+
		"type catalog struct{ *objects }\n"+
		"type objects struct{}\n")
	writeFile(
		t,
		filepath.Join(tmp, "client_parts.go"),
		methodSource("", "r request", "request", 12)+
			methodSource("", "c catalog", "catalog", 12)[len("package sample\n\n"):]+
			methodSource("", "o objects", "object", 12)[len("package sample\n\n"):],
	)

	joined := joinMessages(lintInDir(t, tmp))
	if strings.Contains(joined, `type "left" has`) || strings.Contains(joined, `type "right" has`) {
		t.Fatalf("shared embedded helper counted:\n%s", joined)
	}

	for _, want := range []string{
		`type "big" has 41 methods in 2 files`,
		`type "wide" has 41 methods: 21 of its own in 1 file, plus those from part (20)`,
		`type "client" has 41 methods: 5 of its own in 1 file, plus those from catalog (12), objects (12), request (12)`,
	} {
		if !strings.Contains(joined, want) {
			t.Fatalf("expected %q, got:\n%s", want, joined)
		}
	}
}

